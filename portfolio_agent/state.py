from typing import TypedDict


class PortfolioAgentState(TypedDict, total=False):
    """What flows between the valuation graph's nodes.

    Two deliberately separate evidence channels:

      - `evidence` is the summarized, id-addressed view that reaches the
        LLM's context and the final output. Compact and quotable.
      - `tool_results` is the full ToolResult per tool id, which the
        deterministic engines (scoring, tier math) compute from. Nothing
        here is ever summarized before the arithmetic runs.

    Keeping them apart is what lets the rationale cite `ev3` while the tier
    engine works off the complete comps distribution behind it.
    """

    # ── Input ──────────────────────────────────────────────────────────────
    domain: str
    # Backtest holdout. When set (YYYY-MM-DD), the ladder prices the domain
    # as of that morning: the domain's own sale and every comp on or after
    # the date are invisible. Live valuations leave this unset.
    comp_as_of: str | None
    # The backtest scores numbers, not prose. Set so the graph stops once
    # the tiers exist and does not spend a model call on the rationale.
    skip_rationale: bool
    # Correlates every log line from one valuation. Generated by the classify
    # node and carried in state because state is how anything crosses a
    # LangGraph node boundary — a contextvar set in one node is gone by the
    # time the next one runs.
    run_id: str
    user_profile_hook: dict | None  # accepted, echoed back, not yet applied

    # ── classify ───────────────────────────────────────────────────────────
    category: str
    category_confidence: float
    # Labels beyond the primary, as (name, confidence). The evidence plan is
    # the union across all of them.
    secondary_categories: list[tuple[str, float]]
    subcategory: str
    sld: str
    tld: str
    words: list[str]
    keywords: list[str]
    typo_of: str | None
    typo_distance: int | None
    typo_severity: str | None
    typo_deflator: float  # multiplicative, applied to every tier
    structural_notes: list[str]

    # ── gather_evidence ────────────────────────────────────────────────────
    evidence: list[dict]
    tool_results: dict[str, dict]
    warnings: list[str]
    # The comp ladder's result: which rung it stopped on and what it found.
    comp_set: list[dict]
    comp_refs: list[dict]
    comp_basis: str
    comp_confidence: float
    comp_notes: list[str]

    # ── score / price ──────────────────────────────────────────────────────
    brand_score: dict | None
    tiers: dict

    # ── synthesize / rationale ─────────────────────────────────────────────
    valuation: dict  # a serialized schema.valuation_output.ValuationOutput
    rationale: str

    # Convenience mirrors of the tier band, kept so callers written against
    # the pre-TierSet output keep working. The tiers themselves are the real
    # answer — see MIGRATION_NOTES.md.
    estimated_value_low: int | None
    estimated_value_high: int | None
