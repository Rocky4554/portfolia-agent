"""
check_domain_status — is this domain actually available to buy?

**The failure this exists for.** Every tier in this engine answers "what is
this domain worth". None of them answered "can you have it". A valuation
that prices forge.ai at $240,000 while forge.ai serves a live company's
homepage is not a useful number, and presenting it without saying so is the
kind of mistake a buyer notices in the first five seconds. The opposite case
is just as bad: pricing an end-user tier at $40,000 for a name sitting on an
Afternic lander with a $12,000 buy-now button.

**Zero credentials, and the honesty that forces.** This uses the stdlib
resolver and one HTTP fetch, so it runs on any machine with no key and no
account. That buys real coverage but rules out real claims. Without a WHOIS
or authoritative DNS lookup we cannot tell an unregistered domain from a
registered one with no A record, so we never say "unregistered" — the status
is `no_dns` and the detail says which two possibilities it collapses. Every
other tool in this package refuses to substitute a number for a missing
signal; this one refuses to substitute a fact for a missing lookup.

**An asking price found here is an ask.** It goes to the listings path, not
the comps path, for the reason `marketplace.py` sets out at length: a comp
is what a buyer paid, an ask is what a seller hopes. Nothing in this module
may reach `TierInputs.comps`.
"""

import asyncio
import re
import socket

import httpx
from selectolax.parser import HTMLParser

from portfolio_agent import config
from portfolio_agent.logging_setup import debug, get_logger, info, warn
from portfolio_agent.tools.common import ToolResult, error_result, mock_result, ok_result

log = get_logger(__name__)

SOURCE = "domain_status"

_TIMEOUT_S = 12.0
# Landers are thin by construction: a domain name, a sentence, a price and a
# form. Measured in VISIBLE TEXT rather than HTML bytes, because markup size
# tracks framework choice rather than content — a React lander can outweigh a
# hand-written article. A page with more prose than this is saying something,
# and a page saying something is a site. Used only to break ties, never alone.
_THIN_PAGE_CHARS = 1_500
# A lander offers one action. A real site navigates. Counted as a second
# opinion so a verbose lander and a terse landing page do not swap places.
_LANDER_MAX_LINKS = 8
_MAX_READ_BYTES = 400_000

STATUSES = ("listed_for_sale", "parked", "developed", "inactive", "no_dns",
            "unregistered", "unknown")

# Hosts that only ever serve a sale page. A redirect landing on one of these
# is conclusive on its own — no keyword matching required, so no false
# positive from a site that merely writes about domain sales.
_MARKETPLACE_HOSTS = {
    "dan.com": "Dan.com",
    "undeveloped.com": "Dan.com",
    "afternic.com": "Afternic",
    "sedo.com": "Sedo",
    "sedoparking.com": "Sedo",
    "hugedomains.com": "HugeDomains",
    "buydomains.com": "BuyDomains",
    "squadhelp.com": "Atom (Squadhelp)",
    "atom.com": "Atom",
    "brandbucket.com": "BrandBucket",
    "namecheap.com": "Namecheap Market",
    "brandpa.com": "BrandPa",
    "efty.com": "Efty",
    "domainagents.com": "DomainAgents",
    "domainmarket.com": "DomainMarket",
}

# Phrases that appear on a sale lander and essentially nowhere else. Matched
# only as a corroborating signal, because "this domain is for sale" is a
# sentence a blog post about domains can also contain.
_FOR_SALE_PHRASES = (
    "this domain is for sale",
    "this domain name is for sale",
    "the domain name is for sale",
    "domain is for sale",
    "buy this domain",
    "purchase this domain",
    "make an offer on this domain",
    "inquire about this domain",
    "the owner of this domain",
    "domain for sale",
)

# Pay-per-click parking. Monetised, but nobody has offered to sell it.
_PARKING_PHRASES = (
    "related searches",
    "sponsored listings",
    "this webpage was generated by the domain owner",
    "parked free, courtesy of",
    "domain parking",
)

# A price on a lander, in the currencies these venues quote. Deliberately
# narrow: a loose number regex would pick up a phone number or a year.
_PRICE_RE = re.compile(
    r"(?:US\$|USD\s*\$?|\$|€|£)\s?([0-9]{1,3}(?:,[0-9]{3})+|[0-9]{4,9})(?:\.[0-9]{2})?",
    re.IGNORECASE,
)
_TITLE_RE = re.compile(r"<title[^>]*>(.*?)</title>", re.IGNORECASE | re.DOTALL)
_TAG_RE = re.compile(r"<(script|style)\b.*?</\1>", re.IGNORECASE | re.DOTALL)


async def check_domain_status(domain: str) -> ToolResult:
    """What is currently served at this domain, and can it be bought.

    Returns `{status, venue, asking_price, resolves, final_url, http_status,
    confidence, signals, detail}`. Never raises: a network failure is
    `unknown` with the reason attached, because "we could not check" and
    "nothing is there" are different answers and only one of them is a fact.
    """
    domain = (domain or "").strip().lower().rstrip(".")
    if not domain or "." not in domain:
        return error_result(SOURCE, "domain is empty or has no TLD")

    if config.MOCK_MODE:
        return mock_result(SOURCE, _mock_status(domain))

    resolves = await _resolves(domain)
    if not resolves:
        # The honest limit of a zero-credential check. getaddrinfo cannot
        # distinguish NXDOMAIN from a registered domain that publishes no A
        # record, and guessing between them would put a wrong fact in the
        # report, so the status names both.
        info(log, "lander.no_dns", domain=domain)
        return ok_result(SOURCE, _result(
            domain, status="no_dns", resolves=False, confidence="medium",
            detail=("the domain does not resolve to an address, which means it is either "
                    "unregistered or registered with no DNS configured — this check cannot "
                    "tell those apart without a WHOIS lookup"),
        ))

    page, final_url, http_status, fetch_error = await _fetch(domain)
    if fetch_error is not None:
        warn(log, "lander.fetch_failed", domain=domain, error=fetch_error)
        return ok_result(SOURCE, _result(
            domain, status="unknown", resolves=True, confidence="low",
            detail=f"the domain resolves but could not be fetched ({fetch_error}); "
                   "its sale status is unverified, not absent",
        ))

    verdict = classify_page(domain, page, final_url, http_status)
    info(log, "lander.classified", domain=domain, status=verdict["status"],
         venue=verdict.get("venue"), confidence=verdict["confidence"])
    return ok_result(SOURCE, verdict)


def classify_page(domain: str, html: str, final_url: str, http_status: int) -> dict:
    """The whole decision, as a pure function over a fetched page.

    Separated from the fetch so it can be tested against fixture HTML
    without a network, which is the only way the false-positive cases are
    checkable at all.
    """
    host = _host_of(final_url)
    text = _visible_text(html)
    signals: list[str] = []

    # 1. Redirected onto a marketplace. Conclusive.
    venue = _marketplace_venue(host)
    if venue and not _same_domain(host, domain):
        signals.append(f"resolves to {venue} at {host}")
        return _result(
            domain, status="listed_for_sale", venue=venue, resolves=True,
            asking_price=_asking_price(text), final_url=final_url,
            http_status=http_status, confidence="high", signals=signals,
            detail=f"the domain redirects to a {venue} sale page, so it is on the market now",
        )

    # 2. A marketplace's lander served on the domain itself, identified by
    #    the venue's own script or branding rather than by prose.
    embedded = _embedded_venue(html)
    phrases = [p for p in _FOR_SALE_PHRASES if p in text]
    if embedded:
        signals.append(f"{embedded} lander markup on the domain itself")
        if phrases:
            signals.append(f"sale wording: {phrases[0]!r}")
        return _result(
            domain, status="listed_for_sale", venue=embedded, resolves=True,
            asking_price=_asking_price(text), final_url=final_url,
            http_status=http_status, confidence="high", signals=signals,
            detail=f"a {embedded} sale lander is served at this domain",
        )

    # 3. Sale wording with no venue behind it. Only trusted on a thin page:
    #    a real site that happens to discuss domain sales is not thin, and
    #    calling it "for sale" would be a confident lie about someone's
    #    business.
    links = html.lower().count("<a href")
    thin = len(text) < _THIN_PAGE_CHARS and links <= _LANDER_MAX_LINKS
    if phrases and thin:
        signals.append(f"sale wording: {phrases[0]!r}")
        signals.append(f"lander-shaped ({len(text):,} chars of text, {links} links)")
        return _result(
            domain, status="listed_for_sale", venue=None, resolves=True,
            asking_price=_asking_price(text), final_url=final_url,
            http_status=http_status, confidence="medium", signals=signals,
            detail=("the page offers the domain for sale but names no marketplace, so the "
                    "sale is real but the venue and terms are unconfirmed"),
        )
    if phrases and not thin:
        signals.append(f"sale wording on a substantial page "
                       f"({len(text):,} chars of text, {links} links)")
        return _result(
            domain, status="developed", resolves=True, final_url=final_url,
            http_status=http_status, confidence="low", signals=signals,
            detail=("the page mentions a domain sale but is a full site, which is far more "
                    "likely to be a site that writes about domains than a lander — treated "
                    "as developed, and worth a human glance"),
        )

    # 4. Parked. Monetised, not offered.
    parked = [p for p in _PARKING_PHRASES if p in text]
    if parked:
        signals.append(f"parking markup: {parked[0]!r}")
        return _result(
            domain, status="parked", resolves=True, final_url=final_url,
            http_status=http_status, confidence="medium", signals=signals,
            detail=("the domain serves a parking page, so it is held and monetised but has "
                    "not been offered for sale — acquiring it means approaching the owner"),
        )

    # 5. Nothing meaningful served.
    if http_status >= 400 or len(text) < 200:
        signals.append(f"HTTP {http_status}, {len(text):,} bytes of text")
        return _result(
            domain, status="inactive", resolves=True, final_url=final_url,
            http_status=http_status, confidence="medium", signals=signals,
            detail=("the domain resolves but serves no substantive page — registered and "
                    "unused, which usually means a private owner rather than a listing"),
        )

    title = _page_title(html)
    signals.append(f"live site ({len(text):,} bytes of text)")
    if title:
        signals.append(f"title: {title!r}")
    return _result(
        domain, status="developed", resolves=True, final_url=final_url,
        http_status=http_status, confidence="high", signals=signals,
        detail=("a working site is served at this domain — it is in use, is not listed for "
                "sale, and any price here describes a hypothetical the owner has not invited"),
    )


def _result(domain: str, *, status: str, resolves: bool, confidence: str,
            detail: str, venue: str | None = None, asking_price: int | None = None,
            final_url: str | None = None, http_status: int | None = None,
            signals: list[str] | None = None) -> dict:
    assert status in STATUSES, f"unknown status {status!r}"
    return {
        "domain": domain,
        "status": status,
        "venue": venue,
        # Named `asking_price` and never `price`, so that no consumer can
        # mistake it for something a buyer paid.
        "asking_price": asking_price,
        "resolves": resolves,
        "final_url": final_url,
        "http_status": http_status,
        "confidence": confidence,
        "signals": signals or [],
        "detail": detail,
    }


async def _resolves(domain: str) -> bool:
    loop = asyncio.get_running_loop()
    try:
        await asyncio.wait_for(
            loop.getaddrinfo(domain, 443, type=socket.SOCK_STREAM), timeout=6.0)
        return True
    except (socket.gaierror, asyncio.TimeoutError, OSError, UnicodeError):
        return False


async def _fetch(domain: str) -> tuple[str, str, int, str | None]:
    """One GET, redirects followed, https first. Returns (html, final_url,
    status, error)."""
    headers = {
        # Identifying the agent is the courteous minimum for a tool that
        # touches strangers' servers, and some landers vary on it.
        "User-Agent": "portfolio-agent/1.0 (domain valuation; contact via repo)",
        "Accept": "text/html,application/xhtml+xml",
    }
    last_error = "no attempt made"
    for scheme in ("https", "http"):
        url = f"{scheme}://{domain}/"
        try:
            async with httpx.AsyncClient(
                timeout=_TIMEOUT_S, follow_redirects=True, max_redirects=6,
                headers=headers, verify=scheme == "https",
            ) as client:
                resp = await client.get(url)
                body = resp.text[:_MAX_READ_BYTES]
                debug(log, "lander.fetched", domain=domain, scheme=scheme,
                      status=resp.status_code, bytes=len(body))
                return body, str(resp.url), resp.status_code, None
        except Exception as exc:  # noqa: BLE001 — every failure is the same answer
            last_error = f"{type(exc).__name__}: {exc}"
            debug(log, "lander.fetch_attempt_failed", domain=domain, scheme=scheme,
                  error=last_error)
            # A connect timeout is a failure to reach the HOST, not to
            # negotiate a protocol, so plain HTTP to the same host times out
            # identically. Trying it anyway doubled the worst case to ~24s
            # and made this the slowest step in the entire valuation, to
            # learn nothing the first attempt had not already established.
            if isinstance(exc, httpx.ConnectTimeout):
                break
    return "", "", 0, last_error


def _host_of(url: str) -> str:
    match = re.match(r"^[a-z]+://([^/:]+)", url or "", re.IGNORECASE)
    return match.group(1).lower() if match else ""


def _same_domain(host: str, domain: str) -> bool:
    return host == domain or host.endswith("." + domain)


def _marketplace_venue(host: str) -> str | None:
    for marketplace, label in _MARKETPLACE_HOSTS.items():
        if host == marketplace or host.endswith("." + marketplace):
            return label
    return None


def _embedded_venue(html: str) -> str | None:
    lowered = html.lower()
    for marketplace, label in _MARKETPLACE_HOSTS.items():
        # The venue's own asset host appearing in the markup, which is what a
        # lander embeds and what an ordinary site has no reason to.
        if f"//{marketplace}/" in lowered or f".{marketplace}/" in lowered:
            return label
    return None


def _visible_text(html: str) -> str:
    """The text a reader sees, with scripts and styles gone.

    selectolax rather than the regex this replaces. Stripping tags with a
    regex works until it doesn't: an unclosed tag, a `>` inside an attribute
    or a commented-out block all leak markup into what we then measure as
    "visible text" — and that measurement is what decides whether a page is
    lander-shaped. A real parser handles malformed HTML the way a browser
    does, which is the standard that matters here since a browser is what
    the seller tested their lander in.
    """
    if not html:
        return ""
    try:
        tree = HTMLParser(html)
        for tag in tree.css("script, style, noscript, template"):
            tag.decompose()
        text = tree.body.text(separator=" ") if tree.body else tree.text(separator=" ")
    except Exception:  # noqa: BLE001 — a parser failure must not fail the check
        without_code = _TAG_RE.sub(" ", html)
        text = re.sub(r"<[^>]+>", " ", without_code)
    return re.sub(r"\s+", " ", text or "").strip().lower()


def _page_title(html: str) -> str:
    if not html:
        return ""
    try:
        node = HTMLParser(html).css_first("title")
        if node is not None and node.text():
            return re.sub(r"\s+", " ", node.text()).strip()[:120]
    except Exception:  # noqa: BLE001
        pass
    match = _TITLE_RE.search(html)
    return re.sub(r"\s+", " ", match.group(1)).strip()[:120] if match else ""


def _asking_price(text: str) -> int | None:
    """The largest plausible price on the page.

    Largest rather than first because landers put the buy-now figure below
    an instalment price ("$12,000 or $1,000/mo"), and the instalment is not
    the ask.
    """
    candidates = []
    for raw in _PRICE_RE.findall(text or ""):
        try:
            value = int(raw.replace(",", ""))
        except ValueError:
            continue
        # Below $100 is a subscription or a shipping cost; above $50M is a
        # phone number or a stray digit run.
        if 100 <= value <= 50_000_000:
            candidates.append(value)
    return max(candidates) if candidates else None


def _mock_status(domain: str) -> dict:
    """The mix a real portfolio check returns, not a flattering one.

    Most valued domains are registered and idle; a minority are listed; a
    few are live businesses. Making `developed` reachable in mock mode is
    the point — it is the case that changes the report.
    """
    from portfolio_agent.tools.mocks import _seed, _spread

    seed = _seed(domain, "lander")
    roll = seed % 10
    if roll < 4:
        return _result(domain, status="inactive", resolves=True, confidence="medium",
                       final_url=f"https://{domain}/", http_status=200,
                       signals=["HTTP 200, 41 bytes of text"],
                       detail="the domain resolves but serves no substantive page — registered "
                              "and unused, which usually means a private owner rather than a listing")
    if roll < 6:
        venue = ("Afternic", "Dan.com", "Sedo")[seed % 3]
        return _result(domain, status="listed_for_sale", venue=venue, resolves=True,
                       asking_price=int(_spread(seed, 1, 2_500, 95_000)) // 100 * 100,
                       final_url=f"https://{domain}/", http_status=200, confidence="high",
                       signals=[f"{venue} lander markup on the domain itself"],
                       detail=f"a {venue} sale lander is served at this domain")
    if roll < 8:
        return _result(domain, status="parked", resolves=True, confidence="medium",
                       final_url=f"https://{domain}/", http_status=200,
                       signals=["parking markup: 'related searches'"],
                       detail="the domain serves a parking page, so it is held and monetised but "
                              "has not been offered for sale — acquiring it means approaching the owner")
    if roll < 9:
        return _result(domain, status="developed", resolves=True, confidence="high",
                       final_url=f"https://{domain}/", http_status=200,
                       signals=["live site (8,400 bytes of text)"],
                       detail="a working site is served at this domain — it is in use, is not "
                              "listed for sale, and any price here describes a hypothetical the "
                              "owner has not invited")
    return _result(domain, status="no_dns", resolves=False, confidence="medium",
                   detail="the domain does not resolve to an address, which means it is either "
                          "unregistered or registered with no DNS configured — this check cannot "
                          "tell those apart without a WHOIS lookup")
